TEST(Ton, FormatAmount) {
  char buf[64];

  ton_formatAmount(buf, sizeof(buf), 1000000000ULL);  // 1 TON
  EXPECT_STREQ(buf, "1 TON");

  ton_formatAmount(buf, sizeof(buf), 500000000ULL);  // 0.5 TON
  EXPECT_STREQ(buf, "0.5 TON");

  ton_formatAmount(buf, sizeof(buf), 0);
  EXPECT_STREQ(buf, "0 TON");
}

/* ------------------------------------------------------------------ */
/*  Clear-signing: verify hash reconstruction matches Vault builder    */
/* ------------------------------------------------------------------ */

/* These test vectors are generated by the Vault's TypeScript cell builder
 * (buildTonTransfer in txbuilder/ton.ts). If the firmware's C cell hash
 * reconstruction matches these hashes, clear-signing will work. */

static void hex_to_bytes(const char *hex, uint8_t *out, size_t len) {
  for (size_t i = 0; i < len; i++) {
    unsigned int byte;
    sscanf(hex + 2 * i, "%02x", &byte);
    out[i] = (uint8_t)byte;
  }
}

TEST(Ton, DISABLED_ClearSignPlainTransfer) {
  /* T1: 1 TON, seqno=5, expire=1700000000, bounce=true, no memo */
  const char *to = "EQCD39VS5jcptHL8vMjEXrzGaRcCVYto7HUn4bpAOg8xqB2N";
  uint8_t expected[32];
  hex_to_bytes("4f4614a2b8853e315782c66dc7518b0823eedeeb68f34489a41260df2ce0ee42",
               expected, 32);

  EXPECT_TRUE(ton_verify_transfer_hash(
      to, 1000000000ULL, 5, 1700000000, true,
      NULL, 0, expected));
}

TEST(Ton, DISABLED_ClearSignWithMemo) {
  /* T2: 0.5 TON, seqno=10, expire=1700000100, bounce=true, memo="Hello TON" */
  const char *to = "EQCD39VS5jcptHL8vMjEXrzGaRcCVYto7HUn4bpAOg8xqB2N";
  uint8_t expected[32];
  hex_to_bytes("5a11c7ffa85638d4915c558db081ad983767da265bb8d74eb2a55467a951d293",
               expected, 32);

  EXPECT_TRUE(ton_verify_transfer_hash(
      to, 500000000ULL, 10, 1700000100, true,
      "Hello TON", 9, expected));
}

TEST(Ton, DISABLED_ClearSignNoBounce) {
  /* T3: 2 TON, seqno=1, expire=1700000200, bounce=false, no memo */
  const char *to = "EQCD39VS5jcptHL8vMjEXrzGaRcCVYto7HUn4bpAOg8xqB2N";
  uint8_t expected[32];
  hex_to_bytes("ba57ef391b0d8983202f867d527445487bbf9fb65202296dee11b4be57f91f79",
               expected, 32);

  EXPECT_TRUE(ton_verify_transfer_hash(
      to, 2000000000ULL, 1, 1700000200, false,
      NULL, 0, expected));
}

TEST(Ton, ClearSignWrongAmountFails) {
  /* Same as T1 but with wrong amount — must NOT match */
  const char *to = "EQCD39VS5jcptHL8vMjEXrzGaRcCVYto7HUn4bpAOg8xqB2N";
  uint8_t expected[32];
  hex_to_bytes("4f4614a2b8853e315782c66dc7518b0823eedeeb68f34489a41260df2ce0ee42",
               expected, 32);

  EXPECT_FALSE(ton_verify_transfer_hash(
      to, 999999999ULL, 5, 1700000000, true,
      NULL, 0, expected));
}

TEST(Ton, ClearSignWrongAddressFails) {
  /* Same as T1 but with wrong address — must NOT match */
  uint8_t expected[32];
  hex_to_bytes("4f4614a2b8853e315782c66dc7518b0823eedeeb68f34489a41260df2ce0ee42",
               expected, 32);

  /* Use a different valid address */
  uint8_t pubkey[32];
  memset(pubkey, 0x42, 32);
  char other_addr[TON_ADDRESS_MAX_LEN];
  char raw[TON_RAW_ADDRESS_MAX_LEN];
  ton_get_address(pubkey, true, false, 0, other_addr, sizeof(other_addr),
                  raw, sizeof(raw));

  EXPECT_FALSE(ton_verify_transfer_hash(
      other_addr, 1000000000ULL, 5, 1700000000, true,
      NULL, 0, expected));
}
